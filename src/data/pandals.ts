export function getPandalBySlug(slug: string): PandalPlace | undefined {
  return PANDAL_DATA.find((p) => p.slug === slug);
}

export function getFeaturedPandals(): PandalPlace[] {
  return PANDAL_DATA.filter((p) => p.featured);
}

export function getPandalsByLocality(locality: string): PandalPlace[] {
  return PANDAL_DATA.filter((p) =>
    p.locality.toLowerCase().includes(locality.toLowerCase())
  );
}

export function getPandalById(id: string): PandalPlace | undefined {
  return PANDAL_DATA.find((p) => p.id === id);
}

export function getPandalsByArea(area: string): PandalPlace[] {
  const q = area.toLowerCase().trim();
  return PANDAL_DATA.filter(
    (p) =>
      p.area?.toLowerCase() === q ||
      p.neighborhood?.toLowerCase() === q ||
      p.locality.toLowerCase().includes(q)
  );
}

export function searchPandals(query: string): PandalPlace[] {
  const q = query.toLowerCase().trim();
  if (!q) return [...PANDAL_DATA];
  return PANDAL_DATA.filter(
    (p) =>
      p.name.toLowerCase().includes(q) ||
      p.canonicalName?.toLowerCase().includes(q) ||
      p.nameBengali?.toLowerCase().includes(q) ||
      p.locality.toLowerCase().includes(q) ||
      p.area?.toLowerCase().includes(q) ||
      p.neighborhood?.toLowerCase().includes(q) ||
      p.zone?.toLowerCase().includes(q) ||
      p.description.toLowerCase().includes(q) ||
      p.theme2026?.toLowerCase().includes(q) ||
      p.alternateNames?.some((n) => n.toLowerCase().includes(q))
  );
}

export function getThemedPandals(): PandalPlace[] {
  return PANDAL_DATA.filter((p) => Boolean(p.theme2026 && p.theme2026.trim().length > 0));
}

export function getPandalsByZone(zone: string): PandalPlace[] {
  const z = zone.toLowerCase().trim();
  return PANDAL_DATA.filter((p) => p.zone?.toLowerCase().includes(z));
}

export function getPandalStats() {
  const total = PANDAL_DATA.length;
  const mapped = PANDAL_DATA.filter(
    (p) => typeof p.latitude === "number" && typeof p.longitude === "number"
  ).length;
  const themed = getThemedPandals().length;
  const zones = Array.from(new Set(PANDAL_DATA.map((p) => p.zone).filter(Boolean))) as string[];
  return {
    total,
    mapped,
    pendingGps: total - mapped,
    themed,
    zonesCount: zones.length,
    zones,
  };
}

